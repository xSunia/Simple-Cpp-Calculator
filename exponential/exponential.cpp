#include "requirements.h"

double exponentialExpressions::exp(double a , double n) {
    return std::pow(a,n);
}
double exponentialExpressions::sqrt(double a) {
    return std::sqrt(a);
}
double exponentialExpressions::cqrt(double a) {
    return std::cbrt(a);
}
double exponentialExpressions::log(double a) {
    return std::log(a);
}
double exponentialExpressions::hipo(double a , double b) {
    return std::hypot(a,b);
}