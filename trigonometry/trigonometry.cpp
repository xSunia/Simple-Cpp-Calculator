#include "requirements.h"

double trigonometricExpressions::sin(double a) {
    return std::sin(a);
}
double trigonometricExpressions::cos(double a) {
    return std::cos(a);
}
double trigonometricExpressions::tan(double a) {
    return std::tan(a);
}
double trigonometricExpressions::cot(double a) {
    return std::cos(a) / std::sin(a);
}